# ## 3) Install ADK
# With your environment **activated**, install the Python ADK package:
# ```bash
# # pip path
# pip install google-adk

# # OR uv path
# uv pip install google-adk
# ```
# Optional (latest from GitHub main):
# ```bash
# pip install git+https://github.com/google/adk-python.git
# ```
# Verify:
# ```bash
# pip show google-adk
# adk --version
# adk --help
# ```